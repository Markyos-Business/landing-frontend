import React from "react";
import { inter, thmanya, plexArabic, fontVariables } from "@/app/fonts";

/*
 * The brand's two faces, inside the Payload admin.
 *
 * ── The bug this fixes ────────────────────────────────────────────────────
 *
 * The admin is bilingual in two separate ways: its own interface ships in
 * Arabic (`i18n.supportedLanguages`), and every localised field is edited
 * per locale, so Arabic content is on screen even when the chrome is in
 * English. All of it was rendering in a system fallback — Arial on Windows —
 * because `src/app/fonts.ts` is wired into `src/app/[lang]/layout.tsx` and the admin
 * is a *separate root layout*. The font variables simply were not in scope,
 * and `tailwind/admin.js` named "Thmanya Sans" as if it were an installed family,
 * which on no machine it is.
 *
 * This is the same defect that was found and fixed across the marketing site
 * on 5 Nov 2026 — the admin was the one surface the sweep could not reach,
 * because nothing imports it.
 *
 * ── Why a provider and not an import in the layout ────────────────────────
 *
 * `src/app/(payload)/layout.tsx` is generated by Payload and carries a banner
 * saying not to hand-edit it; its one sanctioned edit is the `tailwind/admin.js`
 * import, which is already spent. `admin.components.providers` is Payload's
 * own extension point for wrapping the panel, so this is the supported seam.
 *
 * ── Why a <style> tag as well as the class ────────────────────────────────
 *
 * `fontVariables` is the three generated class names, and a class only
 * reaches what is inside this component. Payload renders drawers, modals and
 * toasts through portals into <body>, which is outside it — those would have
 * dropped back to the fallback, and a drawer is exactly where somebody edits
 * an Arabic title. So the variables are also declared on `:root` from the
 * font objects' own resolved family names. Both come from the same
 * `next/font` instances as the website: one definition, no second copy of
 * the stack to drift.
 *
 * `display: contents` on the wrapper so it adds a scope and no box — Payload
 * lays the panel out with the template element as a direct child, and a
 * second block element in between would break its grid.
 *
 * ── `--font-latin`, and the trap it exists for ────────────────────────────
 *
 * `next/font` expands `--font-inter` to `Inter, "Inter Fallback"`, and
 * "Inter Fallback" is a metric-adjusted *local* face — Arial on Windows —
 * which does carry Arabic glyphs. Inter carries none, so a stack of
 * `var(--font-inter), var(--font-thmanya)` finds Arabic in Arial and stops
 * one position before the brand face. Measured, not read off the stack:
 * `CSS.getPlatformFontsForNode` on an Arabic post title in this panel
 * reported `Arial x23, Inter x4` while the computed `font-family` named
 * Thmanya the whole time. It is the same defect `tailwind/` documents
 * at `:lang(ar)`.
 *
 * So the skin needs Inter's *primary* family on its own, with Thmanya behind
 * it and the metric fallback behind that. Splitting it here rather than
 * writing "Inter" into the CSS keeps it true if next/font ever hashes the
 * generated name.
 */
export function AdminFonts({ children }: { children: React.ReactNode }) {
  return (
    <>
      <style
        dangerouslySetInnerHTML={{
          __html: `:root{--font-inter:${inter.style.fontFamily};--font-latin:${inter.style.fontFamily.split(",")[0]};--font-thmanya:${thmanya.style.fontFamily};--font-plex-arabic:${plexArabic.style.fontFamily};}`,
        }}
      />
      <div className={fontVariables} style={{ display: "contents" }}>
        {children}
      </div>
    </>
  );
}

export default AdminFonts;
