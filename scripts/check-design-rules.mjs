const findings = [];
let scanned = 0;
let skipped = 0;

for (const rule of RULES) {
  const stripped = rule.comments !== false;
  for (const relRoot of rule.roots) {
    for (const abs of filesUnder(relRoot)) {
      const path = posix(abs);
      if (exemptionFor(rule.id, path)) {
        skipped++;
        continue;
      }

      const source = readFileSync(abs, "utf8");
      scanned++;
      const text = stripped
        ? stripComments(source, { lineComments: extname(abs) !== ".css" })
        : source;

      for (const hit of rule.find(text, path)) {
        const { line, text: excerpt } = locate(source, hit.index);
        findings.push({ rule, path, line, detail: hit.detail, excerpt });
      }
    }
  }
}

findings.sort((a, b) => a.rule.id.localeCompare(b.rule.id) || a.path.localeCompare(b.path) || a.line - b.line);

console.log("");
console.log("  Design system — definition of done (§14)");
console.log("  ──────────────────────────────────────────────────────");

if (findings.length === 0) {
  for (const rule of RULES) {
    console.log(`  ✓ ${rule.title}  ${rule.ref}`);
  }
  console.log("");
  console.log(
    `  ${RULES.length} rules clean across ${scanned} file reads.` +
      ` ${EXEMPTIONS.length} documented exemptions skipped ${skipped} of them.`,
  );
  console.log("  Run with --list to see the rules and why each exemption exists.");
  console.log("");
  process.exit(0);
}

let lastRule = "";
for (const f of findings) {
  if (f.rule.id !== lastRule) {
    console.log("");
    console.log(`  ✗ ${f.rule.title}  ${f.rule.ref}`);
    lastRule = f.rule.id;
  }
  console.log(`      ${f.path}:${f.line}`);
  console.log(`        ${f.detail}`);
  console.log(`        │ ${f.excerpt.slice(0, 110)}`);
}

const byRule = new Map();
for (const f of findings) byRule.set(f.rule.id, (byRule.get(f.rule.id) ?? 0) + 1);

console.log("");
