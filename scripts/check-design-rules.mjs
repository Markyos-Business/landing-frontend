/* ───────────────────────────────────────────────────────────────────────────
 * Walk, match, report
 * ─────────────────────────────────────────────────────────────────────────── */

const EXTENSIONS = new Set([".ts", ".tsx", ".css", ".mjs"]);
const SKIP_DIRS = new Set(["node_modules", ".next", ".git", "dist", "build"]);

function filesUnder(rel) {
  const base = resolve(root, rel);
  if (!existsSync(base)) return [];
  const found = [];
  const walk = (dir) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      if (entry.isDirectory()) {
        if (!SKIP_DIRS.has(entry.name)) walk(resolve(dir, entry.name));
      } else if (EXTENSIONS.has(extname(entry.name))) {
        found.push(resolve(dir, entry.name));
      }
    }
  };
  if (statSync(base).isDirectory()) walk(base);
  else found.push(base);
  return found;
}

const posix = (abs) => relative(root, abs).split(sep).join("/");

const exemptionFor = (ruleId, path) =>
  EXEMPTIONS.find((e) => (e.rule === "*" || e.rule === ruleId) && path.startsWith(e.path));

/** 1-based line number of `index`, and the original line's text. */
function locate(source, index) {
  const before = source.slice(0, index);
  const line = before.split("\n").length;
  const start = before.lastIndexOf("\n") + 1;
  let end = source.indexOf("\n", index);
  if (end === -1) end = source.length;
  return { line, text: source.slice(start, end).trim() };
}

