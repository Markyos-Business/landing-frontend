#!/usr/bin/env node
/*
 * Enforce the design system's "definition of done".
 *
 * ── Why this exists ─────────────────────────────────────────────────────────
 *
 * `MARKYOS-DESIGN-SYSTEM.md` §14 ends with six ripgrep commands that must all
 * return nothing before a migration step counts as finished. They are the
 * right six rules. The problem was never the rules — it was that they lived in
 * a markdown file and ran when somebody remembered to run them, which is to
 * say: after the violation had already shipped.
 *
 * Three sub-12px type sizes shipped on the homepage, one of them at 9px, in
 * sections arguing that Arabic is not an afterthought. §14's own grep for that
 * rule is `text-\[0\.(5|6)[0-9]*rem\]`, which would have found two of the
 * three and misses `text-[0.6875rem]` (11px) and `text-[0.7rem]` entirely. A
 * rule written as a list of the string shapes you happen to have seen is not a
 * rule; it is a record of past bugs. This script parses the number and
 * compares it to the floor, so there is nothing left to enumerate.
 *
 * The other lesson from §14 is the opposite failure. Its physical-properties
 * grep reports `app/globals.css:28` and `components/chrome/Header.tsx:63`,
 * both of which are *comments explaining the rule* — the first says "`margin-
 * inline-start` and never `margin-left`", the second says "`ms-auto` and not
 * `ml-auto`". A gate that cries wolf on its own documentation gets ignored,
 * and then the real hits get ignored with it. So every rule that can be
 * discussed in prose runs against a comment-stripped copy of the file.
 *
 * ── The two modes ───────────────────────────────────────────────────────────
 *
 *   node scripts/check-design-rules.mjs             report and exit 1 on any hit
 *   node scripts/check-design-rules.mjs --list      print the rules and exemptions
 *
 * The first runs inside `npm run check`. There is no soft mode and no warning
 * level on purpose: every rule here is a `Don't` from §13, and a design rule
 * you are allowed to fail is a suggestion.
 *
 * ── Self-contained, deliberately ────────────────────────────────────────────
 *
 * Plain Node, no dependencies, no browser, no sibling checkout. The live
 * checks (`check:bidi`, `check:nav`, `check:pages`) need Chrome and the
 * platform repo beside this one, which means they cannot run in CI or on a
 * fresh clone. This one can, which is the only reason it is allowed to be the
 * thing that fails a build.
 *
 * ── Where this stops ────────────────────────────────────────────────────────
 *
 * It reads source text. It cannot see a value that only exists after the
 * cascade, a size that comes out of a token it did not resolve, or a weight
 * passed through a variable — `fontWeight: d.weight` is invisible to it, and
 * so is anything the CMS sends down at runtime. It catches the class of
 * mistake that is typed into a file, which is where all six of §14's rules
 * live. Visual review still happens on a real page.
 */

